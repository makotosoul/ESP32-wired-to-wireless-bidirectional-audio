echo "Scanning for connected boards..."
PORTS=($(arduino-cli board list | grep "serial" | awk '{print $1}'))

if [ ${#PORTS[@]} -lt 2 ]; then
    echo "Error: Found less than 2 serial boards (${#PORTS[@]} found)."
    echo "Please ensure both ESP32s are connected to your computer."
    exit 1
fi

